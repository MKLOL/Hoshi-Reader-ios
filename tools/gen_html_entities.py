#!/usr/bin/env python3
"""Generate the HTML5 entity tables the sentence segmenters use, from Python's own `html` module.

The desktop pre-translation tool segments chapters through `html.parser` with
`convert_charrefs=True`, i.e. every text run passes through `html.unescape`. Both apps must decode
character references identically or their sentence offsets drift from the stored translations, so
they ship this table (all 2,231 HTML5 names, including the legacy semicolon-less forms) and the
`html.unescape` replacement rules, generated from the same source the tool uses.

Usage: python3 tools/gen_html_entities.py [--swift PATH] [--kotlin PATH]
Defaults write Features/Reader/Sentence/HtmlEntities.swift and, when the Android repo is a sibling
checkout at ../Hoshi-Reader-Android, its HtmlEntities.kt.
"""
import argparse
import html
from html.entities import html5
from pathlib import Path

HEADER = "Generated by tools/gen_html_entities.py from Python {ver}'s html.entities.html5. Do not edit."


def packed_table() -> str:
    lines = []
    for name in sorted(html5):
        value = html5[name]
        lines.append(f"{name} {','.join(format(ord(ch), 'x') for ch in value)}")
    return "\n".join(lines)


def invalid_charrefs() -> list[tuple[int, str]]:
    return sorted(html._invalid_charrefs.items())


def swift_source() -> str:
    import sys
    ver = ".".join(map(str, sys.version_info[:3]))
    refs = ",\n".join(
        f"        0x{num:02x}: \"{''.join(f'\\u{{{ord(ch):x}}}' for ch in value)}\"" for num, value in invalid_charrefs()
    )
    body = packed_table().replace("\\", "\\\\")
    return f"""//
//  HtmlEntities.swift
//  Hoshi Reader
//
//  SPDX-License-Identifier: GPL-3.0-or-later
//
//  {HEADER.format(ver=ver)}
//
//  The tables `html.unescape` uses, so the sentence segmenter decodes character references
//  exactly like the desktop pre-translation tool (`html.parser`, `convert_charrefs=True`).
//

nonisolated enum HtmlEntities {{
    /// Every HTML5 named reference, keyed with its trailing `;` where the standard has one; the
    /// legacy names that also work without a semicolon appear a second time without it.
    static let table: [String: String] = {{
        var out: [String: String] = [:]
        out.reserveCapacity(2400)
        for line in packed.split(separator: "\\n") {{
            guard let space = line.firstIndex(of: " ") else {{ continue }}
            let name = String(line[..<space])
            var value = String.UnicodeScalarView()
            for hex in line[line.index(after: space)...].split(separator: ",") {{
                if let code = UInt32(hex, radix: 16), let scalar = Unicode.Scalar(code) {{ value.append(scalar) }}
            }}
            out[name] = String(value)
        }}
        return out
    }}()

    /// `html._invalid_charrefs`: numeric references the standard maps to other characters.
    static let invalidCharrefs: [UInt32: String] = [
{refs},
    ]

    /// `html._invalid_codepoints`: numeric references that decode to nothing at all.
    static func isInvalidCodepoint(_ code: UInt32) -> Bool {{
        switch code {{
        case 0x1...0x8, 0xB, 0xE...0x1F, 0x7F...0x9F, 0xFDD0...0xFDEF: return true
        default: return (code & 0xFFFE) == 0xFFFE && code <= 0x10FFFF
        }}
    }}

    private static let packed = \"\"\"
{body}
\"\"\"
}}
"""


def kotlin_source() -> str:
    import sys
    ver = ".".join(map(str, sys.version_info[:3]))
    refs = ",\n".join(
        f"        0x{num:02x} to \"{''.join(f'\\u{ord(ch):04x}' for ch in value)}\"" for num, value in invalid_charrefs()
    )
    body = packed_table().replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")
    packed = body.replace("\n", "\\n")
    assert len(packed.encode("utf-8")) < 60000, "constant too large for a JVM string literal"
    return f"""package moe.antimony.hoshi.features.reader.sentence

// {HEADER.format(ver=ver)}
//
// The tables `html.unescape` uses, so the sentence segmenter decodes character references exactly
// like the desktop pre-translation tool (`html.parser`, `convert_charrefs=True`).

internal object HtmlEntities {{
    /**
     * Every HTML5 named reference, keyed with its trailing `;` where the standard has one; the
     * legacy names that also work without a semicolon appear a second time without it.
     */
    val table: Map<String, String> by lazy {{
        val out = HashMap<String, String>(2400)
        for (line in PACKED.split('\\n')) {{
            val space = line.indexOf(' ')
            if (space < 0) continue
            val value = StringBuilder()
            for (hex in line.substring(space + 1).split(',')) {{
                hex.toIntOrNull(16)?.takeIf {{ Character.isValidCodePoint(it) }}?.let {{ value.appendCodePoint(it) }}
            }}
            out[line.substring(0, space)] = value.toString()
        }}
        out
    }}

    /** `html._invalid_charrefs`: numeric references the standard maps to other characters. */
    val invalidCharrefs: Map<Int, String> = mapOf(
{refs},
    )

    /** `html._invalid_codepoints`: numeric references that decode to nothing at all. */
    fun isInvalidCodepoint(code: Int): Boolean = when (code) {{
        in 0x1..0x8, 0xB, in 0xE..0x1F, in 0x7F..0x9F, in 0xFDD0..0xFDEF -> true
        else -> (code and 0xFFFE) == 0xFFFE && code <= 0x10FFFF
    }}

    private const val PACKED = "{packed}"
}}
"""


def main() -> None:
    parser = argparse.ArgumentParser()
    root = Path(__file__).resolve().parent.parent
    parser.add_argument("--swift", type=Path, default=root / "Features/Reader/Sentence/HtmlEntities.swift")
    parser.add_argument(
        "--kotlin", type=Path,
        default=root.parent / "Hoshi-Reader-Android/app/src/main/java/moe/antimony/hoshi/features/reader/sentence/HtmlEntities.kt",
    )
    args = parser.parse_args()
    args.swift.write_text(swift_source(), encoding="utf-8")
    print("wrote", args.swift)
    if args.kotlin.parent.is_dir():
        args.kotlin.write_text(kotlin_source(), encoding="utf-8")
        print("wrote", args.kotlin)
    else:
        print("skipped Kotlin (no Android checkout at", args.kotlin.parent, ")")


if __name__ == "__main__":
    main()
